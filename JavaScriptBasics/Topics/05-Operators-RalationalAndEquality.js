//Relational (comparison) operators - we use them to compare values on their right and left side.
//x > y; x < y;- x is more than y and less than y.
// x >= y; x <= y;- x is higher or equal to y and lower or equal to y.
let value = 3 > 1
console.log(value); //returns true.

//Equality operators
let x = 1;
console.log(x == '1'); //true - lose comparison, it does not check data type of the value. 
console.log(x === '1'); //false - strict comparison, it checks data type as well, as its value.

